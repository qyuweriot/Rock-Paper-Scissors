/** 粉砕 (SPEC §10.1) — 最も処理順に敏感なユニット */

import type { EffectHooks } from './context';

/**
 * 特性「撃破再生」: 相手を倒した場合、HPが全回復する。
 *
 * SPEC §10.1 が定める技1の解決順:
 *   1. 相手へのダメージを適用
 *   2. 自分に反動50を適用
 *   3. 相手の瀕死判定
 *   4. 相手が瀕死になっていれば → 自分をHP全回復   ← このフック
 *   5. 自分の瀕死判定
 *
 * **4 が 5 より前にある**のが要点。HP50 に対して反動が50なので、
 * この順序を取り違えると「常に自滅」か「常に生存」のどちらかになる。
 * battle.ts はHPの増減をすべて済ませてから瀕死処理をすることでこれを実現している。
 *
 * 帰結:
 * - 撃破成功 → 反動50を受けていても全回復して生存
 * - 撃破失敗 → HP50 − 反動50 で確実に自滅
 * - 同段で相手の攻撃も受け、かつ撃破成功 → 全回復により生存
 * - 相手がハサミムシ → これは「回復」なので無効化され、撃破成功でも自滅 (SPEC §10.6)
 */
export const funsaiRegrowth: EffectHooks = {
  onKill: ({ api, self }) => {
    api.heal(self, api.def(self).maxHp);
  },
};
