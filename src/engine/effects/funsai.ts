/** 粉砕 (SPEC §10.1) — 最も処理順に敏感なユニット */

import type { EffectHooks } from './context';

/**
 * 特性「不撓」: 相手を倒した場合、反動が無効になる。
 *
 * SPEC §10.1 が定める技1の解決順:
 *   1. 相手へのダメージを適用
 *   2. 相手の瀕死判定(自分の攻撃で倒したか)
 *   3. 倒していれば反動を無効化 / 倒していなければ反動35を適用   ← このフック
 *   4. 自分の瀕死判定
 *
 * **2 が 3 より前にある**のが要点。反動を適用してから撃破を判定すると、
 * 反動で自滅した相手まで「倒した」と数えてしまう。
 * battle.ts は技ダメージを適用した直後に撃破を確定させ、それを `killed` として渡す。
 *
 * `killed` は**自分の攻撃で倒した場合のみ** true。相手が自分の反動で自滅した場合や、
 * 反射で落ちた場合は含まない (SPEC §10.1)。粉砕ミラーで互いに「相手が倒れた」と
 * 誤認するのを防ぐための区別。
 *
 * 帰結:
 * - 撃破成功 → 反動を受けない。削られていたHPはそのまま残る
 * - 撃破失敗 → 反動35。HP50 なので満タンからでも2回目で自滅する
 * - **これは「回復」ではないので、ハサミムシの治癒封じでは止められない** (SPEC §10.6)
 */
export const funsaiFortitude: EffectHooks = {
  onModifyRecoil: ({ recoil, killed }) => (killed ? 0 : recoil),
};
