/**
 * 評価関数の重み。
 *
 * **engine/constants.ts には置かない。** あちらは「バランス調整はこの2ファイルの変更だけで
 * 完結する」(PLAN §309) という契約を持つファイルで、AI の都合を混ぜると
 * 何がゲーム仕様で何が AI の癖なのか区別できなくなる。
 * ここの値を変えてもゲームのバランスは変わらない。変わるのは AI の打ち筋だけ。
 *
 * 単位は「HP割合1体ぶん = 1.0」。
 */

/** HP割合1体ぶんの価値。他の重みはこれを基準にした相対値 */
export const WEIGHT_HP = 1.0;

/** 撃破 / 被撃破。HP0 の時点で WEIGHT_HP ぶんは既に差がついているので、その上乗せ分 */
export const WEIGHT_FAINT = 1.0;

/** 毒1スタック。ターン終了ごとに10入り続けるので、おおよそ2ターンぶんを見込む */
export const WEIGHT_POISON = 0.15;

/**
 * 設置1枚。**1手のシミュレーションでは効果が出ない**(登場時にしか踏まないため)ので、
 * 明示的な項として与えないと AI は設置を一度も撒かない。
 */
export const WEIGHT_HAZARD = 0.1;

/**
 * 攻勢修正1ポイント。**1手のシミュレーションでは効果が出ない**(次のターン以降に効く)ので、
 * 明示的な項として与えないと AI は一閃の「構え」を一度も使わない。
 *
 * +10 は「場に残る間、毎ターン10ダメージ増える」。残り2〜3ターンとして20〜30HP、
 * HP100の相手なら 0.2〜0.3 ぶん。1ポイントあたり 0.02 とする。
 * ここを大きくしすぎると一閃が積んでばかりで殴らなくなる。
 */
export const WEIGHT_ATK_MOD = 0.02;

/**
 * 不利対面から有利対面へ逃げる価値 (PLAN §268「不利対面なら交代」)。
 *
 * 1手先しか見ない評価では**交代は必ず「殴られ損」に見える**ため、
 * この加点がないと AI は一度も交代しない。
 * 逆に大きくしすぎると両者が交代し合って膠着するので、
 * 交代先のHP条件 (SWITCH_MIN_HP_RATIO) と併せて抑える。
 */
export const SWITCH_DISADVANTAGE_BONUS = 0.3;

/** これ未満のHP割合のユニットは逃げ先にしない。瀕死寸前のユニットを差し出さないため */
export const SWITCH_MIN_HP_RATIO = 0.5;
